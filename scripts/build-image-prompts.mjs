// Generates image-prompts.md — one locked-recipe prompt per food, grouped by
// category so a generation session covers one batch. See specs/04-image-spec.md.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const foodsDir = join(root, "data", "foods");

const RECIPE =
  "Single subject centred on a flat warm sand #F1E7D6 background, three-quarter view from " +
  "about 30 degrees above, one soft key light from the upper left, soft contact shadow beneath. " +
  "Matte painted texture with soft brush edges, no outlines, muted earthy palette. " +
  "3:2 landscape, subject fills about two thirds of the frame. " +
  "No text, no hands, no branding, no props, no white background.";

// Raw ingredients sit bare; a dish or drink needs a vessel, so the vessel itself
// is locked to one description rather than left to the model.
const VESSEL = {
  dish: "Served in a plain unglazed earthenware bowl, no cutlery, no garnish styling.",
  drink: "In a plain clear glass, no straw, no garnish, no coaster.",
  default: "Shown loose with no plate, bowl or cutlery.",
};

const CATEGORY_ORDER = ["fruit", "vegetable", "grain", "spice", "protein", "dairy", "drink", "dish"];
const CATEGORY_LABEL = {
  fruit: "Fruits", vegetable: "Vegetables", grain: "Grains", spice: "Spices & condiments",
  protein: "Proteins", dairy: "Dairy", drink: "Drinks", dish: "Dishes",
};

const foods = readdirSync(foodsDir)
  .filter(f => f.endsWith(".json"))
  .flatMap(f => JSON.parse(readFileSync(join(foodsDir, f), "utf8")));

// Trailing punctuation would double up inside the prompt sentence.
const hint = food => food.description.replace(/\s*[.!]$/, "");

const lines = [
  "# Taseer — food image prompts",
  "",
  "**Generated by `scripts/build-image-prompts.mjs` — do not edit by hand.**",
  "Recipe and acceptance criteria: [specs/04-image-spec.md](specs/04-image-spec.md).",
  "",
  `${foods.length} prompts. Generate one category per session — style consistency holds`,
  "best within a batch. Save each result as `assets/food-images/<id>.png` at 1280×854,",
  "then run `node scripts/optimise-images.mjs`.",
  "",
];

for (const category of CATEGORY_ORDER) {
  const batch = foods.filter(f => f.category === category).sort((a, b) => a.id.localeCompare(b.id));
  if (!batch.length) continue;
  lines.push(`## ${CATEGORY_LABEL[category]} (${batch.length})`, "");
  for (const food of batch) {
    lines.push(
      `### \`${food.id}.png\` — ${food.name}`,
      "",
      "```",
      `Soft painted gouache illustration of ${food.name.toLowerCase()}, ${hint(food).toLowerCase()}. ` +
        `${VESSEL[food.category] ?? VESSEL.default} ${RECIPE}`,
      "```",
      "",
    );
  }
}

writeFileSync(join(root, "image-prompts.md"), lines.join("\n"));
console.log(`Wrote image-prompts.md — ${foods.length} prompts across ${CATEGORY_ORDER.length} batches`);
