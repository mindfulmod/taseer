// Writes assets/data/illustrated.js — the ids that currently have painted art.
//   node scripts/build-illustrated.mjs
//
// Run after dropping new images into assets/food-images/. The card itself does
// NOT depend on this being fresh: it always emits an <img> and falls back to
// the emoji on error (ART.md §8). The manifest exists so the prototype's food
// picker can offer an "illustrated only" filter without probing 250 URLs.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "assets", "food-images");

const ids = readdirSync(dir)
  .filter(f => /\.(jpg|jpeg|png|webp)$/i.test(f))
  .map(f => f.replace(/\.[^.]+$/, ""))
  .sort();

const out = join(root, "assets", "data", "illustrated.js");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/build-illustrated.mjs — do not edit by hand.\n` +
    `export const ILLUSTRATED = new Set(${JSON.stringify(ids)});\n`,
);

console.log(`Wrote ${ids.length} illustrated ids → ${out.replace(root + "/", "")}`);
