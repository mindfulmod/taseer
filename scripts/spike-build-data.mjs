// SPIKE ONLY — not part of the real build pipeline, not wired into CLAUDE.md's
// validation gate. Throwaway script for claude/taseer-dataset-spike, measuring
// whether splitting assets/data/foods.js (1.7MB, statically imported by every
// view via assets/js/data.js) into a slim synchronous index + per-food fetched
// detail is worth doing for real.
//
// Emits:
//   assets/data/foods-index.js  — small ES module, statically imported like the
//                                  old foods.js was. Enough per food for list/
//                                  card display and search-by-name/description:
//                                  id, name, aliases, category, cuisines,
//                                  commonness, emoji, description, and a
//                                  PRECOMPUTED heat/heatClass (so nothing at
//                                  runtime needs the full thermal object just
//                                  to colour a badge). Also carries META,
//                                  PREPARATIONS, SOURCES — all small already.
//   assets/data/detail/<id>.json — one JSON file per food with everything else
//                                  (thermal, histamine, nutrition, remedy,
//                                  guna, effects, stimulant, ingredients),
//                                  fetched on demand when that one food's card
//                                  is actually opened.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const foodsDir = join(root, "data", "foods");
const outDir = join(root, "assets", "data");
const detailDir = join(outDir, "detail");
const indexFile = join(outDir, "foods-index.js");

// ---- same thermal-composite logic as assets/js/data.js, duplicated here on
// purpose: this is a throwaway spike script, not a shared module, and it only
// needs to run once per build to bake `heat`/`heatClass` into the index. ----
const HEAT = {
  tcm: { cold: -1, cool: -0.5, neutral: 0, warm: 0.5, hot: 1 },
  ayurveda: { cooling: -0.7, heating: 0.7 },
  unani: { cold: -1, "cold-dry": -1, "cold-moist": -1, neutral: 0, hot: 1, "hot-dry": 1, "hot-moist": 1 },
};
const SYSTEMS = ["tcm", "ayurveda", "unani"];
function compositeHeat(food) {
  const sum = SYSTEMS.reduce((n, sys) => n + (HEAT[sys][food.thermal[sys].verdict] ?? 0), 0);
  return Math.max(-1, Math.min(1, sum / 3 / 0.9));
}
function heatClass(heat) {
  if (heat <= -0.7) return "cold";
  if (heat <= -0.2) return "cool";
  if (heat < 0.2) return "neutral";
  if (heat < 0.7) return "warm";
  return "hot";
}

const foods = [];
const seen = new Set();

for (const file of readdirSync(foodsDir).filter(f => f.endsWith(".json")).sort()) {
  const batch = JSON.parse(readFileSync(join(foodsDir, file), "utf8"));
  for (const food of batch) {
    if (seen.has(food.id)) {
      console.error(`FATAL: duplicate id "${food.id}" (${file})`);
      process.exit(1);
    }
    seen.add(food.id);
    foods.push(food);
  }
}
foods.sort((a, b) => a.id.localeCompare(b.id));

const sources = JSON.parse(readFileSync(join(root, "data", "sources.json"), "utf8"));
const preparations = JSON.parse(readFileSync(join(root, "data", "preparations.json"), "utf8"));

const meta = {
  count: foods.length,
  categories: foods.reduce((acc, f) => ((acc[f.category] = (acc[f.category] ?? 0) + 1), acc), {}),
  aliases: foods.reduce((n, f) => n + f.aliases.length, 0),
};

// ---- slim index: everything Home + Find's list/card chrome needs, nothing
// that only a single opened food card needs. ----
const index = foods.map(f => ({
  id: f.id,
  name: f.name,
  aliases: f.aliases,
  emoji: f.emoji,
  category: f.category,
  cuisines: f.cuisines,
  commonness: f.commonness,
  description: f.description,
  heat: compositeHeat(f),
  heatClass: heatClass(compositeHeat(f)),
}));

mkdirSync(outDir, { recursive: true });
writeFileSync(
  indexFile,
  [
    "// GENERATED by scripts/spike-build-data.mjs — SPIKE ONLY, do not wire into the real build.",
    "// Slim per-food index: enough for list/card chrome + name/description search.",
    "// Full per-food detail (thermal, histamine, nutrition, guna, effects, ...) lives",
    "// in assets/data/detail/<id>.json, fetched on demand — see assets/js/data.js.",
    `export const META = ${JSON.stringify(meta)};`,
    `export const SOURCES = ${JSON.stringify(sources)};`,
    `export const PREPARATIONS = ${JSON.stringify(preparations)};`,
    `export const INDEX = ${JSON.stringify(index)};`,
    "",
  ].join("\n"),
);

// ---- per-food detail files: everything (full raw record — some duplication
// with the index is fine here, this is a spike, not a bandwidth-optimal format).
rmSync(detailDir, { recursive: true, force: true });
mkdirSync(detailDir, { recursive: true });
for (const f of foods) {
  writeFileSync(join(detailDir, `${f.id}.json`), JSON.stringify(f));
}

const idxKb = (Buffer.byteLength(readFileSync(indexFile)) / 1024).toFixed(1);
const detailBytes = foods.reduce((n, f) => n + Buffer.byteLength(JSON.stringify(f)), 0);
const avgDetailB = (detailBytes / foods.length).toFixed(0);
console.log(`Built assets/data/foods-index.js — ${meta.count} foods, ${idxKb} KB`);
console.log(`Built ${foods.length} files under assets/data/detail/ — ${(detailBytes / 1024).toFixed(1)} KB total, ~${avgDetailB} B/food average`);
