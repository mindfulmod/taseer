// Content versions let shell updates retain unchanged artwork and refresh edits.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const versions = {};
for (const folder of ['food-images', 'food-thumbs', 'prep-images', 'prep-thumbs']) {
  for (const name of readdirSync(new URL(`assets/${folder}/`, root)).filter(f => f.endsWith('.webp')).sort()) {
    const path = `assets/${folder}/${name}`;
    versions[path] = createHash('sha256').update(readFileSync(new URL(path, root))).digest('hex').slice(0, 16);
  }
}
const output = new URL('assets/data/artwork-manifest.js', root);
writeFileSync(output, `// Generated by scripts/build-artwork-manifest.mjs; do not edit.\nconst ARTWORK_VERSIONS = ${JSON.stringify(versions, null, 2)};\n`);
console.log(`Versioned ${Object.keys(versions).length} artwork files in ${fileURLToPath(output)}`);
